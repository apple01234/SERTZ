#
# VSCode Extension configuration.
#
# This configuration module is generated by the VSCode extension.
#
# You don't have to modify anything here manually, this script will be
# recreated automatically if a setting in the VSCode extension is changed.
# 
#
module ScriptLoaderConfiguration
  #
  # Path to the preload scripts folder inside the game project's folder.
  #
  # The script loader will preload these scripts before starting the process.
  #
  # This path can point to a bundle file, a loose script file or a folder.
  #
  # If pointing to a folder, it must contain a load order file.
  #
  # Note: Leave it empty if you don't want to preload scripts.
  #
  PRELOAD_PATH = ''

  #
  # Path to the scripts folder inside the game project's folder.
  #
  # This folder must contain the script files you work with in VSCode.
  #
  # Note: The load order file is expected to exist inside this folder!
  #
  SCRIPTS_PATH = './Scripts'

  #
  # Path to the log file created when the game crashes.
  #
  # The extension uses this file to get information about the exception.
  #
  ERROR_FILE_PATH = '.rgss-script-editor\game.log'

  #
  # Path to the log file used by the script loader to log info.
  #
  # This file is useful for XP and VX which does not have a console.
  #
  LOG_FILE_PATH = '.rgss-script-editor\loader.log'

  #
  # Enables/disables logging.
  #
  LOGGING = false
end

