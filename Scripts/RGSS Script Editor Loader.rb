#
# Script loader.
#
module ScriptLoader
  include ScriptLoaderConfiguration
  
  # Script loader error message.
  LOAD_ERROR_MSG = "If you are reading this it's because something went " \
  "horribly wrong when loading scripts.\n\nThe game couldn't load any " \
  "script so the game will stop after closing this message instantly.\n\n" \
  "Check the load order to make sure scripts in there exist!"
  
  # Standard null output on Unix-like systems.
  NULL_OUTPUT_UNIX = "/dev/null"

  # Standard null output on Windows system.
  NULL_OUTPUT_WIN = "NUL"

  #
  # Reset script loader.
  #
  class ResetLoader < StandardError; end


  #
  # Checks if the platform is Windows-like
  #
  # @return [Boolean]
  #
  def self.windows?
    (/mswin|mingw|cygwin/ =~ RUBY_PLATFORM) != nil
  end

  #
  # Checks if the platform is Unix-like
  #
  # @return [Boolean]
  #
  def self.unix?
    (/linux|darwin/ =~ RUBY_PLATFORM) != nil
  end

  #
  # Checks if the project's version is RGSS1.
  #
  # @return [Boolean] Project is RGSS1.
  #
  def self.rgss1?
    File.file?("Data/Scripts.rxdata")
  end

  #
  # Checks if the project's version is RGSS2.
  #
  # @return [Boolean] Project is RGSS2.
  #
  def self.rgss2?
    File.file?("Data/Scripts.rvdata")
  end
  
  #
  # Checks if the project's version is RGSS3.
  #
  # @return [Boolean] Project is RGSS3.
  #
  def self.rgss3?
    File.file?("Data/Scripts.rvdata2")
  end
  
  #
  # Checks if the game is currently running in test mode.
  #
  # @return [Boolean] Test mode.
  #
  def self.test?
    $DEBUG || $TEST || $BTEST
  end

  #
  # Checks if the given string (str) starts with the specified substring.
  #
  # @param str [String] String.
  # @param substr [String] Substring.
  #
  # @return [Boolean] String starts with substring.
  #
  def self.starts_with?(str, substr)
    return !(str =~ /^#{Regexp.escape(substr)}/).nil?
  end

  #
  # Checks if the given entry is a valid entry to load.
  #
  # Used to process entries from a load order file.
  #
  # @param entry [String] Load order entry.
  #
  # @return [Boolean] Entry validness.
  #
  def self.valid_entry?(entry)
    return false unless entry.is_a?(String)
    return false unless File.extname(entry).downcase == '.rb'
    return false if starts_with?(entry, '#')
    true
  end

  #
  # Loader run logic
  #
  def self.run
    begin
      ensure_file_descriptor_validness
      File.delete(LOG_FILE_PATH) if LOGGING && File.file?(LOG_FILE_PATH)

      # Start-up
      log("Running script loader...")
      log("Preload path is: '#{PRELOAD_PATH}'")
      log("Scripts folder path is: '#{SCRIPTS_PATH}'")
      log("Game error log file path is: '#{ERROR_FILE_PATH}'")
      log("Loader log file path is: '#{LOG_FILE_PATH}'")
      log("Loader logging: #{LOGGING}")
      @scripts = 0
      @scripts_preload = 0

      # Preload scripts
      log('Preloading scripts...')
      preload_order_path = File.join(PRELOAD_PATH, 'load_order.txt')
      if File.file?(PRELOAD_PATH)
        log("Preload path points to a specific file")

        # Try to load it as a RPG Maker bundle data file.
        # Avoids forcing a specific extension as long as the format matches.
        preloaded = load_bundle(PRELOAD_PATH)

        # Try to load it as a loose script if failed
        if preloaded.nil?
          log('Preload file was not a bundle file, loading it normally.')
          preloaded = load_scripts(PRELOAD_PATH)
          @scripts_preload = preloaded
        end
      elsif File.file?(preload_order_path)
        log("Preload path is a folder with a load order file")
        @scripts_preload = load_scripts(preload_order_path)
      else
        log("There are not scripts to preload!")
      end

      # Load scripts
      log('Loading scripts...')
      load_order_path = File.join(SCRIPTS_PATH, 'load_order.txt')
      if File.file?(load_order_path)
        @scripts = load_scripts(load_order_path)
      else
        log("There are not scripts to load!")
      end
    rescue ResetLoader
      log("Restarting script loader...")
      retry
    rescue => e
      # Creates the error log file directory
      create_dir(File.dirname(ERROR_FILE_PATH))

      # Notifies VSCode extension of the error
      File.open(ERROR_FILE_PATH, 'wb') do |file|
        file.write(process_exception(e))
      end

      # Raises again the exception to kill the process
      raise
    end

    # Post-run
    if @scripts_preload == 0 && @scripts == 0
      raise StandardError.new(LOAD_ERROR_MSG)
    end
  end

  #
  # Loads all scripts from a RPG Maker bundle file.
  #
  # Returns nil if the bundle file is invalid.
  # 
  # @param path [String] Bundle file path.
  #
  # @return [Integer] Scripts loaded.
  #
  def self.load_bundle(path)
    log("Loading bundle file from: '#{path}'")
    bundle = read_bundle(path)
    if bundle.nil?
      log("Failed to load bundle file: invalid format")
      return nil
    end

    # Loads each bundle entry
    bundle.each do |entry|
      script_name = entry[1]
      script_contents = entry[2]
      log("Loading bundle script: '#{script_name}'")
      eval_script(script_contents, path)
    end

    # Returns the number of scripts loaded
    bundle.size
  end
  
  #
  # Loads all scripts from a load order file.
  #
  # Path can be a loose Ruby script file.
  # 
  # @param path [String] Bundle file path.
  #
  # @return [Integer] Scripts loaded.
  #
  def self.load_scripts(path)
    return 0 unless File.file?(path)

    file_name = File.basename(path)
    file_dir = File.dirname(path)
    loaded = 0

    # Loads all scripts or loose script.
    if file_name == 'load_order.txt'
      log("Loading scripts using load order: '#{path}'")
      load_order = File.read(path).split("\n")
      load_order.each do |entry|
        unless valid_entry?(entry)
          log("Skipping: '#{entry}'")
          next
        end
        
        script_path = File.expand_path(entry.chomp, file_dir)
        unless File.file?(script_path)
          log("Cannot load: '#{entry}' it is either missing or not a file.")
          next
        end

        log("Loading script: '#{entry}'")
        script_contents = File.read(script_path)
        eval_script(script_contents, script_path)
        loaded += 1
      end
    else
      log("Loading loose script file: '#{path}'")
      script_contents = File.read(path)
      eval_script(script_contents, path)
      loaded += 1
    end
    loaded
  end

  #
  # Decompress data.
  #
  # @param string [String] Data
  #
  # @return [String]
  #
  def self.inflate(string)
    zstream = Zlib::Inflate.new
    buf = zstream.inflate(string)
    zstream.finish
    zstream.close
    buf
  end

  #
  # Reads a bundle file.
  #
  # Returns nil if the bundle file is not valid.
  #
  # @param path [String] Bundle path
  #
  # @return [Array]
  #
  def self.read_bundle(path)
    begin
      bundle = File.open(path, 'rb') { |f| Marshal.load(f) }
      bundle.each { |section| section[2] = inflate(section[2]) }
      bundle
    rescue
      nil
    end
  end

  #
  # Evaluates the script contents into the game.
  #
  # @param string [String] Script contents
  # @param filename [String] Script file name
  # @param lineno [Integer] Script line
  #
  def self.eval_script(string, filename, lineno = 1)
    Kernel.eval(string, TOPLEVEL_BINDING, filename, lineno)
  end

  #
  # Parses the given exception into a string.
  #
  # VSCode extension can interpret a hash with the following information:
  #   - type: Exception type.
  #   - mesg: Exception message.
  #   - back: Exception backtrace array.
  #
  # @param exception [Exception] Exception instance.
  #
  # @return [String] Exception stringified.
  #
  def self.process_exception(exception)
    Marshal.dump({
      :type => "#{exception.class.name}",
      :mesg => "#{exception.message}",
      :back => exception.backtrace
    })
  end

  #
  # Ensures file descriptor validness to avoid Errno::EBADF errors
  #
  # Sometimes when the process is spawned it raises the following error:
  # Errno::EBADF - Bad file descriptor - <STDOUT> error.
  # This error happens when trying to write to the standard output
  # when running a game made in RPG Maker VX Ace (RGSS3) based on my tests.
  #
  # The only solution that I have found is to force reopening
  # the IO object to the windows console output
  #
  # I have not found a way to detect whether the game has allocated
  # a console or not (without Win32API), so reopening is always executed.
  #
  # In case reopening fails, it is redirected to the null output
  # so it avoids crashes when using $stdout or $stderr.
  #
  def self.ensure_file_descriptor_validness
    return unless rgss3?
    begin
      if windows?
        $stdout.reopen("CONOUT$")
        $stderr.reopen("CONOUT$")
      else
        $stdout.reopen("/dev/stdout")
        $stderr.reopen("/dev/stderr")
      end
    rescue
      if windows?
        $stdout.reopen(NULL_OUTPUT_WIN, 'a')
        $stderr.reopen(NULL_OUTPUT_WIN, 'a')
      else
        $stdout.reopen(NULL_OUTPUT_UNIX, 'a')
        $stderr.reopen(NULL_OUTPUT_UNIX, 'a')
      end
    end
  end

  #
  # Creates a new directory and all subfolders needed
  #
  def self.create_dir(directory)
    path = directory.to_s.split(File::SEPARATOR)
    path.size.times do |i|
      dir = path[0..i].join(File::SEPARATOR)
      Dir.mkdir(dir) unless File.directory?(dir)
    end
  end

  #
  # Gets the number of scripts that were preloaded.
  #
  # @return [Integer] Number of scripts.
  #
  def self.preloaded_scripts
    @scripts_preload
  end

  #
  # Gets the number of scripts that were loaded.
  #
  # @return [Integer] Number of scripts.
  #
  def self.loaded_scripts
    @scripts
  end

  #
  # Logs the message.
  #
  # Logging is deactivated in RGSS1 and RGSS2 to avoid message box spam.
  #
  # @param message [String] Message.
  #
  def self.log(message)
    msg = "[RGSS Script Editor Loader] #{message}\n"
    File.open(LOG_FILE_PATH, 'a') { |f| f.write(msg) } if LOGGING
    print msg if rgss3?
  end
end

# Start loader processing
ScriptLoader.run